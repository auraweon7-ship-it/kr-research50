const mix = (r, st, domain) => {
  const soft = domain === 'hs' || domain === 'hr';
  const raw = [
    [60 + r() * 15, 45 + r() * 12, soft ? 38 + r() * 12 : 28 + r() * 12, soft ? 30 + r() * 15 : 12 + r() * 12][st],
    [16 + r() * 8, 18 + r() * 8, 16 + r() * 8, 12 + r() * 8][st],
    [10 + r() * 8, 14 + r() * 8, 16 + r() * 8, soft ? 25 + r() * 12 : 12 + r() * 8][st],
    [r() * 4, soft ? 3 + r() * 5 : 8 + r() * 10, soft ? 5 + r() * 8 : 22 + r() * 14, soft ? 8 + r() * 10 : 42 + r() * 18][st],
  ];
  const s = raw.reduce((a, b) => a + b, 0), out = raw.map(v => Math.round(v / s * 100));
  out[0] += 100 - out.reduce((a, b) => a + b, 0);
  return out;
};
